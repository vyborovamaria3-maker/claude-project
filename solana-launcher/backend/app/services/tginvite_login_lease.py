"""Owner-scoped Telegram login attempt leases shared between Next.js workers.

The token is generated by the backend, held only in the in-process Telegram
challenge, and never returned to a web browser. Redis must be reachable;
no worker-local fallback is safe for this operation.
"""

from __future__ import annotations

import hmac
import secrets

from redis.asyncio import Redis

LOGIN_LEASE_SECONDS = 600


class TelegramLoginLeaseUnavailable(RuntimeError):
    """Redis cannot safely coordinate Telegram login attempts."""


def _key(owner_id: str) -> str:
    return f"tginvite:login-lease:{owner_id}"


async def acquire_login_lease(redis: Redis | None, owner_id: str) -> str | None:
    if redis is None:
        raise TelegramLoginLeaseUnavailable("Shared login coordination unavailable")
    token = secrets.token_urlsafe(32)
    try:
        acquired = await redis.set(_key(owner_id), token, ex=LOGIN_LEASE_SECONDS, nx=True)
    except Exception as exc:
        raise TelegramLoginLeaseUnavailable("Shared login coordination unavailable") from exc
    return token if acquired else None


async def verify_login_lease(redis: Redis | None, owner_id: str, token: str) -> bool:
    if redis is None:
        raise TelegramLoginLeaseUnavailable("Shared login coordination unavailable")
    try:
        current = await redis.get(_key(owner_id))
    except Exception as exc:
        raise TelegramLoginLeaseUnavailable("Shared login coordination unavailable") from exc
    if isinstance(current, bytes):
        current = current.decode("utf-8")
    return isinstance(current, str) and hmac.compare_digest(current, token)


async def release_login_lease(redis: Redis | None, owner_id: str, token: str) -> bool:
    if redis is None:
        raise TelegramLoginLeaseUnavailable("Shared login coordination unavailable")
    try:
        # A late response cannot clear a new login lease issued to another worker.
        removed = await redis.eval(
            """
            if redis.call('GET', KEYS[1]) == ARGV[1] then
                return redis.call('DEL', KEYS[1])
            end
            return 0
            """,
            1, _key(owner_id), token,
        )
        return bool(removed)
    except Exception as exc:
        raise TelegramLoginLeaseUnavailable("Shared login coordination unavailable") from exc


async def reset_login_lease(redis: Redis | None, owner_id: str) -> None:
    """Explicit authenticated disconnect cancels an outstanding login attempt."""
    if redis is None:
        raise TelegramLoginLeaseUnavailable("Shared login coordination unavailable")
    try:
        await redis.delete(_key(owner_id))
    except Exception as exc:
        raise TelegramLoginLeaseUnavailable("Shared login coordination unavailable") from exc
